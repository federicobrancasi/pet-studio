def _parse(raw: str) -> list[str]:
	rows = raw.split() if raw else []
	rows = rows + [_E] * (GLYPH_H - len(rows))
	return rows[:GLYPH_H]


GLYPHS = {ch: _parse(raw) for ch, raw in _RAW.items()}


@lru_cache(maxsize=4096)
def glyph_image(ch: str, color: tuple, px: int) -> Image.Image:
	"""Returns an RGBA image of a glyph scaled to `px` screen pixels per font pixel."""
	rows = GLYPHS.get(ch, GLYPHS['?'])
	im = Image.new('RGBA', (GLYPH_W, GLYPH_H), (0, 0, 0, 0))
	pix = im.load()
	for y, row in enumerate(rows):
		for x, c in enumerate(row):
			if c == '#':
				pix[x, y] = color
	return im.resize((GLYPH_W * px, GLYPH_H * px), Image.NEAREST)


def text_width(text: str, px: int) -> int:
	if not text:
		return 0
	return (len(text) * ADVANCE - 1) * px


def draw_text(dst: Image.Image, x: int, y: int, text: str, color: tuple, px: int, shadow: tuple | None = None, shadow_offset: int = 1) -> None:
	"""Draws text with its top-left glyph cell at (x, y)."""
	cx = x
	for ch in text:
		if ch != ' ':
			if shadow is not None:
				blit(dst, glyph_image(ch, shadow, px), cx + shadow_offset * px, y + shadow_offset * px)
			blit(dst, glyph_image(ch, color, px), cx, y)
		cx += ADVANCE * px
